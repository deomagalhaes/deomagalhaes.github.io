  // Dinâmica Lunar da Seiva (Astrobotânica prática do Vault)
  function getMoonSapInfo(dateObj) {
    const d = dateObj || new Date();
    const refNewMoon = new Date('2000-01-06T18:14:00Z').getTime();
    const synodicMs = 29.53058867 * 86400000;
    const cycles = (d.getTime() - refNewMoon) / synodicMs;
    const frac = cycles - Math.floor(cycles);
    const age = frac * 29.53058867;

    if (age < 1.84 || age >= 27.69) {
      return { phase: '🌑 Lua Nova', sap: 'Seiva concentrada na base/raízes. Ótima para podas estruturais com mínima perda de seiva.' };
    }
    if (age < 14.0) {
      return { phase: '🌒 Lua Crescente', sap: 'Seiva em fluxo ascendente ativo. Excelente para estaquia, alporquia, desfolha de verão e adubação foliar.' };
    }
    if (age < 16.8) {
      return { phase: '🌕 Lua Cheia', sap: 'Turgor máximo na copa e flores. Ótima para adubação de solo; evite podas severas ou aramações tensas.' };
    }
    return { phase: '🌘 Lua Minguante', sap: 'Seiva refluindo para as raízes. Janela ideal para poda de raízes, transplante e aramação estrutural.' };
  }

  function getCurrentSeasonInfo(dateObj) {
    const d = dateObj || new Date();
    const mIdx = d.getMonth();
    const cal = MONTHLY_CALENDAR_SH[mIdx] || MONTHLY_CALENDAR_SH[0];
    const moon = getMoonSapInfo(d);
    return {
      id: cal.season.toLowerCase(),
      monthName: cal.name,
      name: cal.name + ' • ' + cal.season + ' (Brasil)',
      badge: cal.badge,
      summary: cal.summary,
      tasks: cal.tasks,
      focus: cal.focus,
      moonPhase: moon.phase,
      moonSap: moon.sap
    };
  }

